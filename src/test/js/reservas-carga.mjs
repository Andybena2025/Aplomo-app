import vm from 'node:vm';
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const path=new URL('../../main/resources/static/js/reservas.js',import.meta.url);
const source=readFileSync(path,'utf8');
let enviar,rechazar,llamadas=0,cierres=0;
const error={textContent:''},boton={textContent:'Guardar empresa',disabled:false};
const campos={empresa:{value:'1'},sede:{value:'2',options:[],selectedOptions:[]},salon:{value:'3',options:[],selectedOptions:[]}};
const reserva={elements:{namedItem:n=>campos[n]},addEventListener(){}};
const alta={action:'/empresas',dataset:{altaReserva:'empresa'},elements:{namedItem:()=>null},querySelector:s=>s==='button'?boton:error,addEventListener(_n,fn){enviar=fn;}};
vm.runInNewContext(source,{document:{querySelector:s=>s==='form[data-reserva]'?reserva:{},querySelectorAll:()=>[alta]},window:{AplomoProgreso:{iniciar(){return()=>cierres++;}}},URLSearchParams,FormData:class{*[Symbol.iterator](){yield ['nombre','Nombre conservado'];}},TypeError,fetch(){llamadas++;return new Promise((_ok,no)=>{rechazar=no;});}});
const primera=enviar({preventDefault(){}});
assert.equal(boton.disabled,true);assert.equal(boton.textContent,'Guardando…');
await enviar({preventDefault(){}});assert.equal(llamadas,1,'El segundo envío debe bloquearse');
rechazar(new TypeError('Failed to fetch'));await primera;
assert.match(error.textContent,/No se pudo conectar/);assert.doesNotMatch(error.textContent,/Failed|fetch|TypeError/);
assert.equal(boton.disabled,false);assert.equal(boton.textContent,'Guardar empresa');assert.equal(alta.dataset.enviando,undefined);assert.equal(cierres,1);
assert.equal(campos.empresa.value,'1');assert.equal(campos.sede.value,'2');
const segunda=enviar({preventDefault(){}});assert.equal(llamadas,2,'Debe permitir reintentar');rechazar(new TypeError('NetworkError'));await segunda;
assert.match(error.textContent,/Tus datos siguen escritos/);assert.equal(cierres,2);
console.log('3 escenarios aprobados: bloqueo del doble envío; desconexión en español conservando datos; recuperación y reintento.');
